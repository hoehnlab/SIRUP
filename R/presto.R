#' Write a pRESTO/IgBLAST shell script for spatial receptor consensus calling
#'
#' The generated script mirrors the command sequence in the original
#' `Process_BCRs_post_RAD_cluster_barcode.sh`: cluster within 2 um barcode,
#' merge barcode/cluster headers, align sets, build consensus sequences,
#' assign genes with IgBLAST, and build an AIRR database.
#'
#' @param input_fastas Character vector of spatial FASTA inputs.
#' @param output_db_paths Character vector of final expected AIRR db-pass TSVs.
#'   Used for comments and length checking.
#' @param script_path Path to write the shell script.
#' @param receptor Either `ig` for BCR or `tr` for TCR IgBLAST loci.
#' @param identity Cluster identity threshold.
#' @param consensus_freq Consensus frequency threshold.
#' @param germline_glob Germline FASTA glob for `MakeDb.py`.
#' @param igblast_base Path passed to `AssignGenes.py igblast -b`.
#' @param igblast_exec Path passed to `AssignGenes.py --exec`.
#' @param muscle_exec Path passed to `AlignSets.py --exec`.
#' @param nproc Number of processors for pRESTO steps.
#' @return Invisibly returns `script_path`.
#' @export
writePrestoIgblastScript <- function(input_fastas,
                                        output_db_paths,
                                        script_path,
                                        receptor = c("ig", "tr"),
                                        identity = 0.975,
                                        consensus_freq = 0.51,
                                        germline_glob,
                                        igblast_base = "~/software/igblast",
                                        igblast_exec = "~/software/igblast/bin/igblastn",
                                        muscle_exec = "~/software/muscle3.8.31_i86linux64",
                                        nproc = 8) {
  receptor <- match.arg(receptor)
  if (length(input_fastas) != length(output_db_paths)) {
    rlang::abort("input_fastas and output_db_paths must have the same length.")
  }
  .ensure_dir(script_path)

  quote_vec <- function(x) paste0("  \"", x, "\"", collapse = "\n")
  processed_fastas <- sub("\\.fasta$", sprintf("_ident_%s_barcode_cluster_cluster-pass.fasta", identity), input_fastas)
  reheader_fastas <- sub("\\.fasta$", "_reheader.fasta", processed_fastas)
  aligned_fastas <- sub("\\.fasta$", "_align-pass.fasta", reheader_fastas)
  consensus_fastas <- sub(
    "_cluster-pass_reheader_align-pass\\.fasta$",
    sprintf("_freq_%s_cluster-pass_reheader_align-pass_consensus-pass.fasta", consensus_freq),
    aligned_fastas
  )
  fmt7_paths <- sub("\\.fasta$", "_igblast.fmt7", consensus_fastas)

  lines <- c(
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "",
    "# Generated by SIRAP::writePrestoIgblastScript().",
    "# The final AIRR db-pass paths expected from MakeDb.py are:",
    paste0("# - ", output_db_paths),
    "",
    "input_fastas=(",
    quote_vec(input_fastas),
    ")",
    "cluster_fastas=(",
    quote_vec(processed_fastas),
    ")",
    "reheader_fastas=(",
    quote_vec(reheader_fastas),
    ")",
    "aligned_fastas=(",
    quote_vec(aligned_fastas),
    ")",
    "consensus_fastas=(",
    quote_vec(consensus_fastas),
    ")",
    "fmt7_paths=(",
    quote_vec(fmt7_paths),
    ")",
    "",
    "for i in \"${!input_fastas[@]}\"; do",
    "  input=\"${input_fastas[$i]}\"",
    "  cluster_out=\"${cluster_fastas[$i]}\"",
    "  reheader=\"${reheader_fastas[$i]}\"",
    "  aligned=\"${aligned_fastas[$i]}\"",
    "  consensus=\"${consensus_fastas[$i]}\"",
    "  fmt7=\"${fmt7_paths[$i]}\"",
    "  mkdir -p \"$(dirname \"$cluster_out\")\"",
    "",
    sprintf("  ClusterSets.py set -s \"$input\" -f barcode2um -k cluster --ident %s --cluster vsearch --delim '|' '=' ',' --nproc %s -o \"$cluster_out\"", identity, nproc),
    "  ParseHeaders.py merge -s \"$cluster_out\" -f barcode2um cluster -k barcode2um_cluster --delim '|' '=' ',' --act set",
    sprintf("  AlignSets.py muscle -s \"$reheader\" --delim '|' '=' ',' --nproc %s --bf barcode2um_cluster --exec %s", max(1, floor(nproc / 2)), muscle_exec),
    sprintf("  BuildConsensus.py -s \"$aligned\" -o \"$consensus\" --nproc %s -n 1 -q 20 --freq %s --bf barcode2um_cluster --maxerror 0.1 --maxgap 0.3 --fasta", nproc, consensus_freq),
    sprintf("  AssignGenes.py igblast -s \"$consensus\" -b %s --organism human --loci %s --format blast --exec %s", igblast_base, receptor, igblast_exec),
    sprintf("  MakeDb.py igblast -i \"$fmt7\" -s \"$consensus\" -r %s --extended", germline_glob),
    "done",
    ""
  )

  writeLines(lines, script_path)
  Sys.chmod(script_path, mode = "0755")
  invisible(script_path)
}

.spatialvdj_quote <- function(x) {
  shQuote(path.expand(x))
}

.run_external <- function(command, args, dry_run = FALSE, echo = TRUE) {
  cmdline <- paste(c(command, args), collapse = " ")
  if (echo) {
    message("$ ", cmdline)
  }
  if (isTRUE(dry_run)) {
    return(invisible(cmdline))
  }
  status <- system2(command, args = args, stdout = "", stderr = "")
  if (!identical(status, 0L)) {
    rlang::abort(paste0("Command failed with status ", status, ": ", cmdline))
  }
  invisible(status)
}

.presto_paths <- function(input_fasta, identity, consensus_freq, output_dir = NULL) {
  if (is.null(output_dir)) {
    output_dir <- dirname(input_fasta)
  }
  stem <- tools::file_path_sans_ext(basename(input_fasta))
  cluster <- file.path(
    output_dir,
    sprintf("%s_ident_%s_barcode_cluster_cluster-pass.fasta", stem, identity)
  )
  reheader <- sub("\\.fasta$", "_reheader.fasta", cluster)
  aligned <- sub("\\.fasta$", "_align-pass.fasta", reheader)
  consensus <- file.path(
    output_dir,
    sprintf("%s_ident_%s_barcode_cluster_freq_%s_cluster-pass_reheader_align-pass_consensus-pass.fasta", stem, identity, consensus_freq)
  )
  fmt7 <- sub("\\.fasta$", "_igblast.fmt7", consensus)
  db_pass <- sub("_igblast\\.fmt7$", "_igblast_db-pass.tsv", fmt7)
  list(
    input = input_fasta,
    cluster = cluster,
    reheader = reheader,
    aligned = aligned,
    consensus = consensus,
    fmt7 = fmt7,
    db_pass = db_pass
  )
}

#' Run pRESTO/IgBLAST consensus calling for one spatial FASTA
#'
#' This keeps users inside R while running the external Immcantation/pRESTO
#' command-line tools. Output from each command is printed directly to the R
#' console via `system2(stdout = "", stderr = "")`.
#'
#' @param input_fasta Spatial FASTA written from preprocessed receptor reads.
#' @param output_dir Directory for pRESTO/IgBLAST outputs. Defaults to the
#'   input FASTA directory.
#' @param receptor Either `ig` for BCR or `tr` for TCR IgBLAST loci.
#' @param identity Cluster identity threshold.
#' @param consensus_freq Consensus frequency threshold.
#' @param germline_glob Germline FASTA glob for `MakeDb.py`.
#' @param igblast_base Path passed to `AssignGenes.py igblast -b`.
#' @param igblast_exec Path passed to `AssignGenes.py --exec`.
#' @param muscle_exec Path passed to `AlignSets.py --exec`.
#' @param nproc Number of processors for pRESTO steps.
#' @param cluster_field FASTA header field used for within-spot clustering.
#' @param dry_run Print commands without executing them.
#' @param echo Print each command before running it.
#' @return A named list of output paths, invisibly.
#' @export
processSpatialSample <- function(input_fasta,
                                      output_dir = NULL,
                                      receptor = c("ig", "tr"),
                                      identity = 0.975,
                                      consensus_freq = 0.51,
                                      germline_glob,
                                      igblast_base = "~/software/igblast",
                                      igblast_exec = "~/software/igblast/bin/igblastn",
                                      muscle_exec = "~/software/muscle3.8.31_i86linux64",
                                      nproc = 8,
                                      cluster_field = "barcode2um",
                                      dry_run = FALSE,
                                      echo = TRUE) {
  receptor <- match.arg(receptor)
  paths <- .presto_paths(input_fasta, identity, consensus_freq, output_dir)
  if (!dir.exists(dirname(paths$cluster))) {
    dir.create(dirname(paths$cluster), recursive = TRUE, showWarnings = FALSE)
  }

  delim_args <- c("--delim", shQuote("|"), shQuote("="), shQuote(","))
  half_nproc <- max(1, floor(nproc / 2))

  .run_external(
    "ClusterSets.py",
    c(
      "set", "-s", .spatialvdj_quote(paths$input),
      "-f", cluster_field,
      "-k", "cluster",
      "--ident", as.character(identity),
      "--cluster", "vsearch",
      delim_args,
      "--nproc", as.character(nproc),
      "-o", .spatialvdj_quote(paths$cluster)
    ),
    dry_run = dry_run,
    echo = echo
  )

  .run_external(
    "ParseHeaders.py",
    c(
      "merge", "-s", .spatialvdj_quote(paths$cluster),
      "-f", cluster_field, "cluster",
      "-k", paste0(cluster_field, "_cluster"),
      delim_args,
      "--act", "set"
    ),
    dry_run = dry_run,
    echo = echo
  )

  .run_external(
    "AlignSets.py",
    c(
      "muscle", "-s", .spatialvdj_quote(paths$reheader),
      delim_args,
      "--nproc", as.character(half_nproc),
      "--bf", paste0(cluster_field, "_cluster"),
      "--exec", .spatialvdj_quote(muscle_exec)
    ),
    dry_run = dry_run,
    echo = echo
  )

  .run_external(
    "BuildConsensus.py",
    c(
      "-s", .spatialvdj_quote(paths$aligned),
      "-o", .spatialvdj_quote(paths$consensus),
      "--nproc", as.character(nproc),
      "-n", "1",
      "-q", "20",
      "--freq", as.character(consensus_freq),
      "--bf", paste0(cluster_field, "_cluster"),
      "--maxerror", "0.1",
      "--maxgap", "0.3",
      "--fasta"
    ),
    dry_run = dry_run,
    echo = echo
  )

  .run_external(
    "AssignGenes.py",
    c(
      "igblast", "-s", .spatialvdj_quote(paths$consensus),
      "-b", .spatialvdj_quote(igblast_base),
      "--organism", "human",
      "--loci", receptor,
      "--format", "blast",
      "--exec", .spatialvdj_quote(igblast_exec)
    ),
    dry_run = dry_run,
    echo = echo
  )

  .run_external(
    "MakeDb.py",
    c(
      "igblast", "-i", .spatialvdj_quote(paths$fmt7),
      "-s", .spatialvdj_quote(paths$consensus),
      "-r", germline_glob,
      "--extended"
    ),
    dry_run = dry_run,
    echo = echo
  )

  invisible(paths)
}

#' Run pRESTO/IgBLAST consensus calling for multiple spatial FASTA files
#'
#' @param input_fastas Character vector of spatial FASTA files.
#' @param output_dirs Optional vector of output directories, one per FASTA.
#' @param ... Passed to `runPrestoIgblastSample()`.
#' @return A list of output path lists, invisibly.
#' @export
runPrestoIgblastPipeline <- function(input_fastas,
                                        output_dirs = NULL,
                                        ...) {
  if (is.null(output_dirs)) {
    output_dirs <- rep(NA_character_, length(input_fastas))
  }
  if (length(output_dirs) != length(input_fastas)) {
    rlang::abort("output_dirs must be NULL or the same length as input_fastas.")
  }
  results <- vector("list", length(input_fastas))
  names(results) <- basename(input_fastas)
  for (i in seq_along(input_fastas)) {
    output_dir <- output_dirs[[i]]
    if (is.na(output_dir)) {
      output_dir <- NULL
    }
    message("Processing spatial FASTA ", i, " of ", length(input_fastas), ": ", input_fastas[[i]])
    results[[i]] <- runPrestoIgblastSample(
      input_fasta = input_fastas[[i]],
      output_dir = output_dir,
      ...
    )
  }
  invisible(results)
}
