#!/usr/bin/env python3
"""docs_tools.py - the text-only half of the docs pipeline (no R needed).

Copied into <package>/docs/ by the rtd-r-package-docs skill. It is owned by the
package: edit it freely.

Subcommands (run from the package root):

    python3 docs/docs_tools.py nav      # regenerate the nav block in mkdocs.yml
    python3 docs/docs_tools.py extras   # index.md, news.md, llms.txt, llms-full.txt
    python3 docs/docs_tools.py check    # validate pages, nav, links, strict build
    python3 docs/docs_tools.py get extras.freshness_check   # print one setting (used by CI)
    python3 docs/docs_tools.py freshness-excludes           # git pathspecs the CI stale check skips

Why Python and not R: these steps only read text files (man/*.Rd, DESCRIPTION,
README.md, docs/**/*.md), so they run anywhere, including on Read the Docs where
there is no R. Only Rd->HTML and knitting vignettes need R (docs/build.R).

Configuration lives in docs/docs-config.yml (see that file for every key).
Requires PyYAML (installed with mkdocs).
"""
