# --------------------------------------------------------------------------- config
def load_config(root: Path, path: str) -> dict:
    cfg_path = root / path
    if not cfg_path.exists():
        sys.exit(f"missing {cfg_path}; run the skill's scaffold step first")
    user = yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}
    cfg = {**DEFAULTS, **user}
    cfg["extras"] = {**DEFAULTS["extras"], **(user.get("extras") or {})}
    desc = read_description(root)
    cfg["package"] = cfg["package"] or desc.get("Package")
    cfg["site_name"] = cfg["site_name"] or cfg["package"]
    if not cfg["package"]:
        sys.exit("package name not set in docs-config.yml and not found in DESCRIPTION")
    return cfg


def read_description(root: Path) -> dict:
    """Parse DESCRIPTION (DCF) into {field: value}, joining continuation lines."""
    path = root / "DESCRIPTION"
    out: dict[str, str] = {}
    if not path.exists():
        return out
    key = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if re.match(r"^\s", line) and key:
            out[key] += " " + line.strip()
        elif ":" in line:
            key, val = line.split(":", 1)
            out[key.strip()] = val.strip()
    return out


# --------------------------------------------------------------------------- Rd parsing
def _brace_arg(text: str, start: int) -> tuple[str, int]:
    """Return the balanced {...} argument whose '{' is at text[start]."""
    depth, i = 0, start
    while i < len(text):
        c = text[i]
        if c == "\\":
            i += 2
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i], i + 1
        i += 1
    return text[start + 1:], len(text)


def rd_field(text: str, tag: str) -> list[str]:
    out = []
    for m in re.finditer(r"\\" + tag + r"\{", text):
        arg, _ = _brace_arg(text, m.end() - 1)
        out.append(" ".join(arg.split()))
    return out


def clean_rd_text(s: str) -> str:
    s = re.sub(r"\\(?:code|emph|strong|pkg|file|samp|sQuote|dQuote)\{([^{}]*)\}", r"\1", s)
    s = re.sub(r"\\link(?:\[[^\]]*\])?\{([^{}]*)\}", r"\1", s)
    return s.replace("\\%", "%").replace("\\_", "_")


def parse_rd(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    src = re.search(r"^% Please edit documentation in (\S+)", text, re.M)
    families = []
    for c in rd_field(text, "concept"):
        if re.search(r"Other " + re.escape(c) + r":", text):
            families.append(c)
    names = rd_field(text, "name")
    titles = rd_field(text, "title")
    keywords = rd_field(text, "keyword")
    return {
        "stem": path.stem,
        "name": names[0] if names else path.stem,
        "title": clean_rd_text(titles[0]) if titles else path.stem,
        "aliases": rd_field(text, "alias"),
        "family": families[0] if families else None,
        "source": src.group(1) if src else None,
        "internal": "internal" in keywords,
        "doctype": (rd_field(text, "docType") or [None])[0],
        "n_code_links": len(re.findall(r"\\code\{\\link", text)),
        "n_pkg_links": len(re.findall(r"\\link\[[^\]]*:[^\]]*\]", text)),
    }


def load_topics(root: Path, cfg: dict) -> list[dict]:
    man = root / "man"
    topics = [parse_rd(p) for p in sorted(man.glob("*.Rd"))]
    if not cfg["include_internal"]:
        topics = [t for t in topics if not t["internal"]]
    return topics


# --------------------------------------------------------------------------- grouping
def pretty_source(src: str, package: str = "", titles: dict | None = None) -> str:
    """R/spatial_statistics.R -> "Spatial statistics"; the package name keeps its case.
    A title in the group_titles setting (keyed by file stem) wins."""
    if titles and Path(src).stem in titles:
        return titles[Path(src).stem]
    words = Path(src).stem.replace("_", " ").replace("-", " ").split()
    words = [package if package and w.lower() == package.lower() else w for w in words]
    stem = " ".join(words)
    return stem[:1].upper() + stem[1:]


def group_topics(root: Path, cfg: dict, topics: list[dict]) -> list[tuple[str | None, list[dict]]]:
    """Apply the grouping chain: override file > @family > source file > flat.

    Returns [(group_title_or_None, [topics])]. A single (None, [...]) means flat.
    """
    mode = cfg["grouping"]
    pages = [t for t in topics if t["doctype"] != "package"]
    if mode == "flat":
        return [(None, sorted(pages, key=lambda t: t["name"].lower()))]

    override: dict[str, str] = {}
    order: list[str] = []
    ov_path = root / cfg["nav_groups_file"]
    if ov_path.exists():
        data = yaml.safe_load(ov_path.read_text(encoding="utf-8")) or {}
        for g in data.get("groups", []):
            order.append(g["title"])
            for stem in g.get("topics", []):
                override[stem] = g["title"]
        order = data.get("order", order)

    buckets: dict[str, list[dict]] = {}
    for t in pages:
        if t["stem"] in override:
            g = override[t["stem"]]
        elif t["family"] and mode in ("auto", "family"):
            g = t["family"][:1].upper() + t["family"][1:]   # roxygen families are often lowercase
        elif t["source"] and mode in ("auto", "source"):
            g = pretty_source(t["source"], cfg["package"], cfg["group_titles"])
        else:
            g = "Other"
        buckets.setdefault(g, []).append(t)

    if list(buckets) == ["Other"]:
        return [(None, sorted(pages, key=lambda t: t["name"].lower()))]

    titles = [g for g in order if g in buckets]
    titles += sorted((g for g in buckets if g not in titles and g != "Other"), key=str.lower)
    if "Other" in buckets:
        titles.append("Other")
    return [(g, sorted(buckets[g], key=lambda t: t["name"].lower())) for g in titles]


# --------------------------------------------------------------------------- vignettes
def list_vignettes(root: Path, cfg: dict) -> list[dict]:
    found = []
    for d in cfg["vignette_sources"]:
        for p in sorted((root / d).glob("*.Rmd")) + sorted((root / d).glob("*.qmd")):
            if p.stem in cfg["vignette_exclude"]:
                continue
            m = re.match(r"^---\n(.*?)\n---", p.read_text(encoding="utf-8"), re.S)
            fm = yaml.safe_load(m.group(1)) if m else {}
            title = (fm or {}).get("title") or p.stem
            found.append({"stem": p.stem, "title": str(title)})
    order = cfg["vignette_order"]

    def key(v):
        if v["stem"] in order:
            return (0, order.index(v["stem"]), "")
        if v["stem"].lower() == cfg["package"].lower():
            return (0, -1, "")
        return (1, 0, v["stem"].lower())

    return sorted(found, key=key)


# --------------------------------------------------------------------------- nav
def build_nav(root: Path, cfg: dict) -> tuple[list, int]:
    topics = load_topics(root, cfg)
    groups = group_topics(root, cfg, topics)
    docs = root / "docs"

    about = []
    if cfg["extras"]["index"] or (docs / "index.md").exists():
        about.append({"Introduction": "index.md"})
    pkg_page = next((t for t in topics if t["doctype"] == "package"), None)
    if pkg_page:
        about.append({"Package Overview": f"topics/{pkg_page['stem']}.md"})
    if cfg["extras"]["news"] and (root / "NEWS.md").exists():
        about.append({"Release Notes": "news.md"})
    nav: list = [{"About": about}]

    vigs = list_vignettes(root, cfg)
    if vigs:
        def entry(v: dict) -> dict:
            return {v["title"]: f"vignettes/{v['stem']}.md"}
        by_stem = {v["stem"]: v for v in vigs}
        used: set[str] = set()
        for grp in cfg["vignette_groups"]:
            items = [entry(by_stem[st]) for st in grp.get("vignettes", []) if st in by_stem]
            used.update(grp.get("vignettes", []))
            if items:
                nav.append({grp["title"]: items})
        rest = [v for v in vigs if v["stem"] not in used]
        if rest:
            nav.append({"Vignettes": [entry(v) for v in rest]})

    depth = 2
    if len(groups) == 1 and groups[0][0] is None:
        help_items: list = [{t["name"]: f"topics/{t['stem']}.md"} for t in groups[0][1]]
    else:
        depth = 3  # About/Help Topics -> group -> page; readthedocs theme hides level 3 at depth 2
        help_items = [
            {g: [{t["name"]: f"topics/{t['stem']}.md"} for t in members]} for g, members in groups
        ]
    nav.append({cfg["help_topics_title"]: help_items})
    return nav, depth


def cmd_nav(root: Path, cfg: dict, args) -> int:
    mk = root / "mkdocs.yml"
    if not mk.exists():
        sys.exit("mkdocs.yml not found; run the scaffold step first")
    text = mk.read_text(encoding="utf-8")
    if NAV_BEGIN not in text or NAV_END not in text:
        sys.exit("mkdocs.yml has no generated-nav markers; add them (see assets/templates/mkdocs.yml)")
    nav, depth = build_nav(root, cfg)
    block = yaml.safe_dump({"nav": nav}, sort_keys=False, allow_unicode=True, default_flow_style=False)
    new = re.sub(
        re.escape(NAV_BEGIN) + r".*?" + re.escape(NAV_END),
        lambda _m: f"{NAV_BEGIN}\n{block.rstrip()}\n{NAV_END}",
        text,
        flags=re.S,
    )
    new = re.sub(r"(navigation_depth:\s*)\d+", rf"\g<1>{depth}", new)
    if new != text:
        mk.write_text(new, encoding="utf-8")
    n = sum(len(v) if isinstance(v, list) else 1 for item in nav for v in item.values())
    print(f"nav: wrote {n} top-level entries (navigation_depth={depth})")
    return 0


# --------------------------------------------------------------------------- extras
def _split_top_level(text: str) -> list[str]:
    """Split an R argument list on commas that are not inside quotes or brackets."""
    parts, depth, quote, cur = [], 0, None, []
    for ch in text:
        if quote:
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
            continue
        cur.append(ch)
    parts.append("".join(cur))
    return [p for p in parts if p.strip()]


def _r_strings(text: str) -> list[str]:
    return [a or b for a, b in re.findall(r'"([^"]*)"|\'([^\']*)\'', text)]


def person_names(desc: dict) -> list[str]:
    """Names from Authors@R. Handles person("Given", "Family") and person(given =, family =)."""
    raw = desc.get("Authors@R", "")
    names = []
    for m in re.finditer(r"\bperson\s*\(", raw):
        depth, quote, j = 1, None, m.end()
        while j < len(raw) and depth:
            c = raw[j]
            if quote:
                if c == quote:
                    quote = None
            elif c in "\"'":
                quote = c
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            j += 1
        named, positional = {}, []
        for arg in _split_top_level(raw[m.end():j - 1]):
            kv = re.match(r"\s*(\w+)\s*=\s*(.*)$", arg, re.S)
            if kv:
                named[kv.group(1)] = kv.group(2)
            else:
                positional.append(arg)
        free = [k for k in ("given", "family", "middle", "email", "role", "comment") if k not in named]
        named.update(zip(free, positional))
        given = " ".join(_r_strings(named.get("given", named.get("first", ""))))
        family = " ".join(_r_strings(named.get("family", named.get("last", ""))))
        roles = ", ".join(_r_strings(named.get("role", "")))
        full = f"{given} {family}".strip()
        if full:
            names.append(full + (f" ({roles})" if roles else ""))
    return names or ([desc["Author"]] if desc.get("Author") else [])


def write_generated(path: Path, body: str, force: bool) -> None:
    if path.exists() and GENERATED_MARK not in path.read_text(encoding="utf-8") and not force:
        print(f"extras: skipped {path} (hand-written; pass --force to overwrite)")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{GENERATED_MARK}\n\n{body.rstrip()}\n", encoding="utf-8")
    print(f"extras: wrote {path}")


def raw_url(cfg: dict, rel: str) -> str:
    repo = cfg["repo"] or "OWNER/REPO"
    return f"https://raw.githubusercontent.com/{repo}/{cfg['branch']}/{rel}"


def repo_relative_links(text: str, root: Path, cfg: dict) -> str:
    """README links like (docs/x.md) or (LICENSE) point at repo files, which do not exist
    inside the built site. Send them to GitHub instead so the dead-link check stays honest."""
    if not cfg["repo"]:
        return text

    def fix(m: re.Match) -> str:
        target = m.group(2)
        if re.match(r"^(https?:|mailto:|#|tel:)", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        local = root / path
        if not path or not local.exists():
            return m.group(0)
        kind = "tree" if local.is_dir() else "blob"
        url = f"https://github.com/{cfg['repo']}/{kind}/{cfg['branch']}/{path.lstrip('./')}"
        return f"{m.group(1)}({url}{'#' + anchor if anchor else ''})"

    return re.sub(r"(!?\[[^\]]*\])\(([^)\s]+)\)", fix, text)


# --------------------------------------------------------------------------- llms.json and the agent skill
SKILL_MARK = "<!-- generated by docs/docs_tools.py extras: edit the Rd or vignette sources, not this file -->"


def site_url(cfg: dict, rel: str = "") -> str | None:
    """Address of a page on the Read the Docs site, or None when rtd_slug is not set."""
    if not cfg.get("rtd_slug"):
        return None
    return f"https://{cfg['rtd_slug']}.readthedocs.io/en/latest/" + (rel.strip("/") + "/" if rel else "")


def md_sections(md: str) -> dict:
    """Split a generated topic page into {heading: text} at its '## ' headings."""
    out, key, buf = {}, None, []
    for line in md.splitlines():
        if line.startswith("## "):
            if key is not None:
                out[key] = "\n".join(buf).strip()
            key, buf = line[3:].strip(), []
        elif key is not None:
            buf.append(line)
    if key is not None:
        out[key] = "\n".join(buf).strip()
    return out


def first_sentence(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.+?[.!?])(?:\s|$)", text)
    return m.group(1) if m else text


def first_sentences(text: str, n: int = 2, cap: int = 320) -> str:
    """The first n sentences of a text, cut at cap characters on a sentence end."""
    text = re.sub(r"\s+", " ", text).strip()
    parts = re.findall(r".+?[.!?](?:\s|$)", text) or [text]
    out = ""
    for part in parts[:n]:
        if out and len(out) + len(part) > cap:
            break
        out += part
    return out.strip()


def page_summary(md: str) -> str:
    """Summary of a generated vignette page.

    Use the sentence that starts with "In this page", "This page", or "Here," when the page has one.
    Otherwise use the first two sentences of the first plain paragraph."""
    md = re.sub(r"<div.*?</div>", "", md, flags=re.S)           # callout boxes
    md = re.sub(r"```.*?```", "", md, flags=re.S)               # code
    paras = []
    for para in re.split(r"\n\s*\n", md):
        lines = [l for l in para.strip().splitlines() if l.strip()]
        if not lines or re.match(r"^(#|>|\||<|[=\-]{3,}|[*+-] |\d+\. )", lines[0]) or all(re.match(r"^[=\-]{3,}$", l) for l in lines[1:2]):
            continue
        text = " ".join(lines)
        if len(text) > 40:
            paras.append(text)
    for text in paras[:4]:
        for sent in re.findall(r".+?[.!?](?:\s|$)", re.sub(r"\s+", " ", text)):
            if re.match(r"^(In this page|This page|Here,)", sent.strip()):
                return sent.strip()
    return first_sentences(paras[0]) if paras else ""


def topic_arguments(section: str) -> list[tuple[str, str]]:
    pairs = re.findall(r"^`([^`\n]+)`\n\n:   (.*?)(?=\n\n`[^`\n]+`\n\n:   |\Z)", section, flags=re.S | re.M)
    return [(name, re.sub(r"\s+", " ", text).strip()) for name, text in pairs]


def topic_info(root: Path, t: dict) -> dict:
    """Read the generated page of one topic and pull out the parts that agents need."""
    path = root / "docs" / "topics" / f"{t['stem']}.md"
    md = path.read_text(encoding="utf-8") if path.exists() else ""
    sec = md_sections(md)
    usage = re.search(r"```[ ]*[Rr]?\n(.*?)\n```", sec.get("Usage", ""), flags=re.S)
    return {
        "name": t["name"], "stem": t["stem"], "title": t["title"],
        "aliases": [a for a in t["aliases"] if a != t["name"]],
        "description": re.sub(r"\s+", " ", sec.get("Description", "")).strip(),
        "usage": usage.group(1).strip() if usage else "",
        "arguments": topic_arguments(sec.get("Arguments", "")),
        "value": re.sub(r"\s+", " ", sec.get("Value", "")).strip(),
        "markdown": md.strip(),
    }


def vignette_sections(cfg: dict, vigs: list[dict]) -> list[tuple[str, list[dict]]]:
    """Group the vignettes like the nav does: [(section title, [vignette, ...])]."""
    by_stem = {v["stem"]: v for v in vigs}
    used, out = set(), []
    for grp in cfg["vignette_groups"]:
        items = [by_stem[st] for st in grp.get("vignettes", []) if st in by_stem]
        used.update(grp.get("vignettes", []))
        if items:
            out.append((grp["title"], items))
    rest = [v for v in vigs if v["stem"] not in used]
    if rest:
        out.append(("Vignettes", rest))
    return out


def llms_data(root: Path, cfg: dict, desc: dict, topics: list[dict], vigs: list[dict], full: bool) -> dict:
    """The content of llms.json (full = False) or llms-full.json (full = True)."""
    title = desc.get("Title", cfg["site_name"])
    d = re.sub(r"\s+", " ", desc.get("Description", "")).strip()
    if d.lower().startswith(title.rstrip(".").lower()):
        d = d[len(title.rstrip(".")):].lstrip(". ").strip()

    def entry(kind, ident, name, md_rel, site_rel, extra=None):
        path = root / md_rel
        md = path.read_text(encoding="utf-8").strip() if path.exists() else ""
        e = {"type": kind, "id": ident, "title": name, "source": md_rel, "markdown_url": raw_url(cfg, md_rel)}
        if site_url(cfg, site_rel) or site_rel == "":
            e["url"] = site_url(cfg, site_rel)
        if extra:
            e.update(extra)
        if full:
            e["markdown"] = md
        return e

    pages = [entry("overview", "index", cfg["site_name"], "docs/index.md", "")]
    sections = []
    for sec_title, items in vignette_sections(cfg, vigs):
        rows = []
        for v in items:
            md = (root / f"docs/vignettes/{v['stem']}.md")
            summary = cfg["vignette_summaries"].get(v["stem"]) or (page_summary(md.read_text(encoding="utf-8")) if md.exists() else "")
            rows.append(entry("vignette", v["stem"], v["title"], f"docs/vignettes/{v['stem']}.md",
                              f"vignettes/{v['stem']}", {"section": sec_title, "summary": summary}))
        sections.append({"title": sec_title, "pages": [r["id"] for r in rows]})
        pages += rows
    funcs = []
    for g, members in group_topics(root, cfg, topics):
        for t in members:
            info = topic_info(root, t)
            extra = {"summary": first_sentence(info["description"])}
            if info["aliases"]:
                extra["also_documents"] = info["aliases"]
            if g:
                extra["group"] = g
            funcs.append(entry("function", t["name"], t["title"], f"docs/topics/{t['stem']}.md",
                               f"topics/{t['stem']}", extra))
    data = {
        "name": cfg["site_name"], "title": title, "description": d,
        "version": desc.get("Version"), "license": desc.get("License"),
        "repository": f"https://github.com/{cfg['repo']}" if cfg["repo"] else None,
        "documentation": site_url(cfg),
        "requirements": {k.lower(): re.sub(r"\s+", " ", desc.get(k, "")).strip() for k in ("Depends", "Imports", "Suggests")},
        "full_content": raw_url(cfg, "llms-full.json") if not full else None,
        "index": raw_url(cfg, "llms.json") if full else None,
        "sections": sections,
        "pages": pages,
        "functions": funcs,
    }
    return {k: v for k, v in data.items() if v is not None}


def write_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "functions"


def write_skill_references(root: Path, cfg: dict, topics: list[dict], vigs: list[dict]) -> None:
    """Write the generated reference files of the agent skill. SKILL.md is never touched."""
    if not cfg["skill_dir"] or not cfg["extras"]["skill"]:
        return
    sdir = root / cfg["skill_dir"]
    ref = sdir / "references"
    ref.mkdir(parents=True, exist_ok=True)
    if not (sdir / "SKILL.md").exists():
        print(f"extras: warning, {sdir / 'SKILL.md'} does not exist. Write it by hand; the build never creates it.")

    written = set()

    def write(name: str, body: str) -> None:
        (ref / name).write_text(f"{SKILL_MARK}\n\n{body.rstrip()}\n", encoding="utf-8")
        written.add(name)

    # functions: group by source file even when the site uses a flat list
    skill_cfg = {**cfg, "grouping": "source" if cfg["grouping"] == "flat" else cfg["grouping"]}
    groups = group_topics(root, skill_cfg, topics)
    index = [f"# {cfg['site_name']} function index", "",
             "Each group has its own file with the usage and the arguments of each function.", ""]
    for g, members in groups:
        g = g or "Functions"
        fname = f"functions-{slug(g)}.md"
        index += [f"## {g}", "", f"Details: `references/{fname}`", ""]
        body = [f"# {g}", ""]
        for t in members:
            info = topic_info(root, t)
            also = f" (also: {', '.join('`' + a + '`' for a in info['aliases'])})" if info["aliases"] else ""
            index.append(f"- `{t['name']}`{also}: {t['title']}")
            body += [f"## {t['name']}", "", f"{t['title']}.", ""]
            if info["aliases"]:
                body += ["This topic also documents: " + ", ".join(f"`{a}`" for a in info["aliases"]) + ".", ""]
            if info["description"]:
                body += [info["description"], ""]
            if info["usage"]:
                body += ["```r", info["usage"], "```", ""]
            if info["arguments"]:
                body += ["Arguments:", ""] + [f"- `{n}`: {txt}" for n, txt in info["arguments"]] + [""]
            if info["value"]:
                body += [f"Value: {info['value']}", ""]
        index.append("")
        write(fname, "\n".join(body))
    write("function-index.md", "\n".join(index))

    tut = [f"# {cfg['site_name']} tutorials and guides", ""]
    base = site_url(cfg)
    if base:
        tut += [f"Site: {base}", ""]
    for sec_title, items in vignette_sections(cfg, vigs):
        tut += [f"## {sec_title}", ""]
        for v in items:
            md = root / f"docs/vignettes/{v['stem']}.md"
            summary = cfg["vignette_summaries"].get(v["stem"]) or (page_summary(md.read_text(encoding="utf-8")) if md.exists() else "")
            where = site_url(cfg, f"vignettes/{v['stem']}") or f"docs/vignettes/{v['stem']}.md"
            tut += [f"### {v['title']}", "", f"Page: {where}", "", summary, ""]
    write("tutorials.md", "\n".join(tut))

    # remove generated group files that no longer exist
    for old in ref.glob("functions-*.md"):
        if old.name not in written and SKILL_MARK in old.read_text(encoding="utf-8"):
            old.unlink()
    print(f"extras: wrote {len(written)} skill reference files in {sdir / 'references'}")


def cmd_extras(root: Path, cfg: dict, args) -> int:
    ex, desc, docs = cfg["extras"], read_description(root), root / "docs"
    topics = load_topics(root, cfg)

    if ex["index"]:
        readme = (root / "README.md").read_text(encoding="utf-8") if (root / "README.md").exists() else ""
        readme = repo_relative_links(readme, root, cfg)
        parts = [readme.strip() or f"# {cfg['site_name']}", ""]
        for label, field in (("Depends", "Depends"), ("Imports", "Imports"), ("Suggests", "Suggests")):
            if desc.get(field):
                squeezed = re.sub(r"\s+", " ", desc[field])
                parts.append(f"**{label}:** {squeezed}  ")
        authors = person_names(desc)
        if authors:
            parts += ["", "## Authors", ""] + [f"{a}  " for a in authors]
        if desc.get("License"):
            parts += ["", "## License", "", desc["License"]]
        write_generated(docs / "index.md", "\n".join(parts), args.force)

    if ex["news"] and (root / "NEWS.md").exists():
        write_generated(docs / "news.md", (root / "NEWS.md").read_text(encoding="utf-8"), args.force)

    formats = ex["llms_formats"] if isinstance(ex["llms_formats"], list) else [ex["llms_formats"]]
    if ex["llms"] and "json" in formats:
        vigs_json = list_vignettes(root, cfg)
        write_json(root / "llms.json", llms_data(root, cfg, desc, topics, vigs_json, full=False))
        write_json(root / "llms-full.json", llms_data(root, cfg, desc, topics, vigs_json, full=True))
        print("extras: wrote llms.json and llms-full.json")

    if ex["llms"] and "txt" in formats:
        title = desc.get("Title", cfg["site_name"])
        d = re.sub(r"\s+", " ", desc.get("Description", "")).strip()
        # Some packages start Description with the Title. Do not print the title twice.
        if d.lower().startswith(title.rstrip(".").lower()):
            d = d[len(title.rstrip(".")):].lstrip(". ").strip()
        lines = [f"# {cfg['site_name']}", "", f"> {title}. {d}".strip(), ""]
        lic = desc.get("License", "")
        lines += [f"Source: https://github.com/{cfg['repo']} - License: {lic}" if cfg["repo"] else f"License: {lic}", ""]
        lines += [
            "All links point at raw files in the GitHub repo, not the readthedocs site,",
            "so any agent that can fetch a URL can read them directly.",
            "",
            "## Getting started",
            "",
            f"- [Introduction]({raw_url(cfg, 'docs/index.md')})",
        ]
        vigs = list_vignettes(root, cfg)
        if vigs:
            lines += ["", "## Vignettes (tutorials)", ""]
            lines += [f"- [{v['title']}]({raw_url(cfg, 'docs/vignettes/' + v['stem'] + '.md')})" for v in vigs]
        lines += ["", "## Function reference", "",
                  f"All URLs share the prefix {raw_url(cfg, 'docs/topics/')} (e.g. `fn` -> `.../topics/fn.md`).", ""]
        for g, members in group_topics(root, cfg, topics):
            if g:
                lines += [f"### {g}"]
            lines += [f"- `{t['name']}`: {t['title']}" for t in members]
            lines.append("")
        lines += ["## Optional", ""]
        if (root / "NEWS.md").exists() and ex["news"]:
            lines.append(f"- [Release notes]({raw_url(cfg, 'docs/news.md')})")
        lines.append(f"- [Full site content in one file]({raw_url(cfg, 'llms-full.txt')})")
        (root / "llms.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("extras: wrote llms.txt")

        full = []
        pages = ["docs/index.md"]
        pages += [f"docs/vignettes/{v['stem']}.md" for v in vigs]
        pages += [f"docs/topics/{t['stem']}.md" for t in topics]
        for rel in pages:
            p = root / rel
            if p.exists():
                full.append(f"\n\n---\n\n<!-- source: {rel} -->\n\n{p.read_text(encoding='utf-8').strip()}\n")
        (root / "llms-full.txt").write_text(f"# {cfg['site_name']} - full documentation\n" + "".join(full), encoding="utf-8")
        print("extras: wrote llms-full.txt")

    write_skill_references(root, cfg, topics, list_vignettes(root, cfg))
    return 0


# --------------------------------------------------------------------------- check
LINK_RE = re.compile(r"(?<!\\)!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
LEFTOVER_RES = [
    (re.compile(r"\\(?:link|code|href)\{"), "unconverted Rd markup"),
    (re.compile(r"vignette\(\s*[\"'][^\"']+[\"']"), "unrewritten vignette() reference"),
]


def nav_paths(nav) -> list[str]:
    out = []
    if isinstance(nav, list):
        for item in nav:
            out += nav_paths(item)
    elif isinstance(nav, dict):
        for v in nav.values():
            out += nav_paths(v)
    elif isinstance(nav, str):
        out.append(nav)
    return out


def strip_fences(text: str) -> str:
    return re.sub(r"(```|~~~).*?\1", "", text, flags=re.S)


def cmd_check(root: Path, cfg: dict, args) -> int:
    errors: list[str] = []
    warns: list[str] = []
    docs = root / "docs"
    topics = load_topics(root, cfg)

    mk_path = root / "mkdocs.yml"
    nav = []
    if mk_path.exists():
        # mkdocs.yml may contain python tags in some projects; tolerate them
        loader = type("L", (yaml.SafeLoader,), {})
        loader.add_multi_constructor("tag:yaml.org,2002:python/", lambda l, s, n: None)
        nav = (yaml.load(mk_path.read_text(encoding="utf-8"), Loader=loader) or {}).get("nav", [])
    else:
        errors.append("mkdocs.yml missing")
    in_nav = set(nav_paths(nav))

    for t in topics:
        rel = f"topics/{t['stem']}.md"
        if not (docs / rel).exists():
            errors.append(f"no page for man/{t['stem']}.Rd (expected docs/{rel}) - run Rscript docs/build.R")
        if rel not in in_nav:
            errors.append(f"docs/{rel} is not in the nav - run python3 docs/docs_tools.py nav")
    for rel in in_nav:
        if not (docs / rel).exists():
            errors.append(f"nav points at missing page docs/{rel}")
    known = {t["stem"] for t in load_topics(root, {**cfg, "include_internal": True})}
    if (docs / "topics").exists():
        for p in (docs / "topics").glob("*.md"):
            if p.stem not in known:
                warns.append(f"orphan page docs/topics/{p.name} has no man/{p.stem}.Rd (stale? delete it)")

    ignored = [(docs / p).resolve() for p in cfg["ignore_paths"]]

    def is_ignored(p: Path) -> bool:
        return any(i == p.resolve() or i in p.resolve().parents for i in ignored)

    for md in sorted(docs.rglob("*.md")):
        if is_ignored(md):
            continue
        text = strip_fences(md.read_text(encoding="utf-8"))
        for m in LINK_RE.finditer(text):
            target = m.group(1)
            if re.match(r"^(https?:|mailto:|#|tel:)", target):
                continue
            path_part = target.split("#", 1)[0]
            if path_part and not (md.parent / path_part).resolve().exists():
                errors.append(f"dead link in {md.relative_to(root)}: {target}")
        for m in re.finditer(r'<img\s[^>]*src="([^"]+)"', text):
            # The home page (docs/index.md) is served at the site root, so its relative paths are right.
            if md != docs / "index.md" and not re.match(r"^(https?:|data:|/)", m.group(1)):
                errors.append(
                    f"raw HTML image with a relative path in {md.relative_to(root)}: {m.group(1)} "
                    "(MkDocs does not rewrite it, so it breaks on the site; use Markdown image syntax)")
        if md.parent.name in ("topics", "vignettes"):
            for rx, why in LEFTOVER_RES:
                if rx.search(text):
                    warns.append(f"{md.relative_to(root)}: {why}")

    if args.external:
        seen = set()
        for md in sorted(docs.rglob("*.md")):
            if is_ignored(md):
                continue
            for m in LINK_RE.finditer(strip_fences(md.read_text(encoding="utf-8"))):
                url = m.group(1)
                if url.startswith("http") and url not in seen:
                    seen.add(url)
                    try:
                        req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": "docs-check"})
                        urllib.request.urlopen(req, timeout=10)
                    except Exception as e:  # noqa: BLE001
                        warns.append(f"external link failed ({md.relative_to(root)}): {url} ({e})")

    if shutil.which("mkdocs") and not args.no_build and mk_path.exists():
        with tempfile.TemporaryDirectory() as tmp:
            # Do not add -q here. It hides warnings, and --strict then never fails.
            r = subprocess.run(["mkdocs", "build", "--strict", "-d", tmp, "-f", str(mk_path)],
                               capture_output=True, text=True, cwd=root)
            if r.returncode != 0:
                errors.append("mkdocs build --strict failed:\n" + (r.stdout + r.stderr).strip()[-1500:])
    elif not args.no_build:
        warns.append("mkdocs not installed; skipped the strict build (pip install -r docs/requirements.txt)")

    for w in warns:
        print("WARN ", w)
    for e in errors:
        print("ERROR", e)
    print(f"check: {len(topics)} topics, {len(errors)} errors, {len(warns)} warnings")
    if args.json:
        Path(args.json).write_text(json.dumps({"errors": errors, "warnings": warns}, indent=2))
    return 1 if errors else 0


# --------------------------------------------------------------------------- CI helpers
def cmd_get(root: Path, cfg: dict, args) -> int:
    """Print one setting. Booleans print as true/false so a shell `if` can read them."""
    if not args.key:
        sys.exit("get needs a key, for example: get extras.freshness_check")
    value = cfg
    for part in args.key.split("."):
        if not isinstance(value, dict) or part not in value:
            sys.exit(f"no such setting: {args.key}")
        value = value[part]
    print(str(value).lower() if isinstance(value, bool) else value)
    return 0


def cmd_freshness_excludes(root: Path, cfg: dict, args) -> int:
    """Print one git pathspec per line for the CI stale check to skip."""
    for path in cfg["freshness_exclude"]:
        print(f":!{path}")
    return 0


# --------------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["nav", "extras", "check", "get", "freshness-excludes"])
    ap.add_argument("key", nargs="?", help="get: setting to print, with dots for nesting (extras.llms)")
    ap.add_argument("--root", default=".")
    ap.add_argument("--config", default="docs/docs-config.yml")
    ap.add_argument("--force", action="store_true", help="extras: overwrite hand-written pages")
    ap.add_argument("--external", action="store_true", help="check: also HEAD-request external links (network)")
    ap.add_argument("--no-build", action="store_true", help="check: skip mkdocs build --strict")
    ap.add_argument("--json", help="check: also write results to this JSON file")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    cfg = load_config(root, args.config)
    commands = {"nav": cmd_nav, "extras": cmd_extras, "check": cmd_check,
                "get": cmd_get, "freshness-excludes": cmd_freshness_excludes}
    return commands[args.command](root, cfg, args)


if __name__ == "__main__":
    sys.exit(main())
